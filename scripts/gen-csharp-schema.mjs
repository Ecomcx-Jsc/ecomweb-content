// Sinh bảng thuộc tính khối / định dạng chữ cho máy chủ (C#) từ CORE_NODES / CORE_MARKS của gói này — hai bên luôn khớp, không chép tay.
// Chạy:  node scripts/gen-csharp-schema.mjs <đường dẫn ContentSchema.g.cs>   (sau `npm run build`)
import { writeFileSync } from "node:fs";
import { CORE_NODES, CORE_MARKS } from "../dist/index.js";

const out = process.argv[2];
if (!out) { console.error("Thiếu đường dẫn đầu ra"); process.exit(1); }
const str = (s) => JSON.stringify(s);
const num = (n) => (Number.isInteger(n) ? String(n).replace(/(\d)(?=(\d{3})+$)/g, "$1_") : String(n));
function attr(spec) {
  const T = { string: "T.Str", url: "T.Url", number: "T.Num", integer: "T.Int", boolean: "T.Bool", json: "T.Json" }[spec.type];
  if (!T) throw new Error(`kiểu lạ: ${spec.type}`);
  const parts = [T];
  if (spec.min !== undefined) parts.push(`Min: ${num(spec.min)}`);
  if (spec.max !== undefined) parts.push(`Max: ${num(spec.max)}`);
  if (spec.enum) {
    if (!spec.enum.every((v) => typeof v === "string")) throw new Error("enum không phải chuỗi");
    parts.push(`Enum: [${spec.enum.map(str).join(", ")}]`);
  }
  if (spec.pattern) parts.push(`Pattern: ${str(spec.pattern)}`);
  return `new(${parts.join(", ")})`;
}
function table(name, nodes) {
  const lines = [`    internal static readonly Dictionary<string, Dictionary<string, ContentFormat.Attr>> ${name} = new()`, "    {"];
  for (const [k, v] of Object.entries(nodes)) {
    const attrs = Object.entries(v.attrs ?? {});
    if (!attrs.length) { lines.push(`        [${str(k)}] = new(),`); continue; }
    lines.push(`        [${str(k)}] = new()`, "        {");
    for (const [a, spec] of attrs) lines.push(`            [${str(a)}] = ${attr(spec)},`);
    lines.push("        },");
  }
  lines.push("    };");
  return lines.join("\n");
}
const src = `// <auto-generated>
// Sinh bằng content/scripts/gen-csharp-schema.mjs từ CORE_NODES / CORE_MARKS của @ecomcx/ecomweb-content — ĐỪNG sửa tay; đổi schema ở gói content rồi chạy lại script.
// </auto-generated>
using T = Cms.Application.Content.ContentFormat.T;

namespace Cms.Application.Content;

/// <summary>Bảng thuộc tính khối và định dạng chữ lõi (cùng nghĩa với coerceAttr của gói content).</summary>
internal static class ContentSchema
{
${table("Nodes", CORE_NODES)}

${table("Marks", CORE_MARKS)}
}
`;
writeFileSync(out, src);
console.log(`đã ghi ${out}: ${Object.keys(CORE_NODES).length} khối, ${Object.keys(CORE_MARKS).length} định dạng`);
